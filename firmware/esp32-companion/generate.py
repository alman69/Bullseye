#!/usr/bin/env python3
"""Build the single uploadable sketch from the tested display/scooper modules."""
from pathlib import Path
import argparse
import re

HERE = Path(__file__).resolve().parent
FIRMWARE = HERE.parent
DISPLAY = FIRMWARE / "esp32-display/bullseye_display"
SCOOPER = FIRMWARE / "esp32-scooper/bullseye_scooper"
OUTPUT = HERE / "bullseye_companion/bullseye_companion.ino"
PARTS = [*(DISPLAY / name for name in ("PixelFace.h", "DisplayProtocol.h", "DisplayJson.h", "DisplayRenderer.h", "TouchInput.h", "DisplayInput.h")),
         *(SCOOPER / name for name in ("ScooperConfig.h", "Scooper.h")),
         HERE / "ServoPwm.h", HERE / "ArduinoServoPwm.h",
         HERE / "CompanionHttp.h", HERE / "CompanionControl.h", HERE / "CompanionBle.h", HERE / "CompanionRuntime.h"]


def render():
    text = ["// Bullseye Companion: ONE FILE for ESP32-S3 display + scooper over ONE BLE connection.\n"
            "// Generated by firmware/esp32-companion/generate.py. No repository headers needed to upload.\n"
            "// Core 3.3.12 / 32MB OPI flash / OPI PSRAM / Default 4MB with spiffs / CDC disabled.\n"
            "// Existing DFRobot_GDL, Adafruit GFX and BusIO libraries remain required.\n"
            "// Servos: GPIO39/40, separate 5V supply sharing GND; both command 90 degrees on boot.\n"]
    for part in PARTS:
        source = re.sub(r'^#pragma once\s*$', '', part.read_text(), flags=re.M)
        source = re.sub(r'^#include "[^"\n]+"\s*$', '', source, flags=re.M)
        text.append("\n// ===== " + str(part.relative_to(FIRMWARE)) + " =====\n" + source)
    runtime = (DISPLAY / "bullseye_display.ino").read_text()
    runtime = re.sub(r'^#include "[^"\n]+"\s*$', '', runtime, flags=re.M)
    runtime = runtime.replace("// Bullseye standalone BLE display. No Wi-Fi, rover commands, or vehicle code.",
                              "// Display/BLE runtime, sharing the loop with the independent scooper controller.")
    runtime = runtime.replace("DFRobot_ST7365P_320x480_HW_SPI screen", "companion::Runtime companionController;\n\nDFRobot_ST7365P_320x480_HW_SPI screen", 1)
    runtime = runtime.replace("class ServerCallbacks :", (HERE / "CompanionGatt.inc").read_text() + "\nclass ServerCallbacks :", 1)
    runtime = runtime.replace("receiver.reset();", "receiver.reset(); companionController.mailbox.reset();")
    runtime = runtime.replace("  service->start();", "  beginControlGatt(service);\n  service->start();", 1)
    runtime = runtime.replace("  beginBle();\n}", "  companionController.begin();\n  beginBle();\n}", 1)
    runtime = runtime.replace("void loop() {\n", "void loop() {\n  companionController.poll(millis());\n", 1)
    runtime = runtime.replace("  if (advertise) server->startAdvertising();", "  if (advertise) server->startAdvertising();\n  pollControlGatt(millis());", 1)
    runtime = runtime.replace("    renderer.render(screen, model, touchReady ? touchController.name() : \"unavailable\", now);",
                              "    companionController.updateMotion(millis());\n    renderer.render(screen, model, touchReady ? touchController.name() : \"unavailable\", now);\n    companionController.updateMotion(millis());", 1)
    text.append("\n// ===== Shared Arduino setup and loop =====\n" + runtime)
    result = "\n".join(text)
    assert '#include "' not in result, "Uploadable sketch must be self-contained"
    assert result.count('void setup()') == 1 and result.count('void loop()') == 1
    assert 'companionController.poll(millis());' in result and 'companionController.begin();' in result
    assert '#include <WiFi.h>' not in result and 'NetworkServer' not in result
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit("Combined sketch is out of date; run generate.py")
        print("Single-file companion sketch matches its source modules.")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected)
        print(OUTPUT)


if __name__ == "__main__":
    main()
